"""Imported provider/model catalogue (OmniRoute snapshot, MIT) with provenance.

The data file ``registry/data/omniroute_catalog.json`` is generated by ``scripts/import_omniroute_catalog.py``
(see docs/CATALOG.md). Everything in it is **advertised**: a third-party research snapshot, not a primary
source. The rules that keep OASIS Route's guarantees intact:

- Imported models are stored with ``lifecycle = "catalog"``. They are listed, previewed and explained, but the
  router never dispatches to them until the provider's own authenticated model list confirms them (which
  flips them to ``active``).
- Imported free-tier claims never set ``Model.pricing.free``. Only the provider itself (its model list or
  account API) or a reviewed primary source can make a model free. Imported claims become ``discovered``
  offers with evidence pointing at the snapshot, so they appear in the *advertised* capacity layer and in the
  review queue, never in *verified*.
- Imported prices are estimates (``pricing.verified = false``) used for worst-case cost reservation.
- Providers the import classifies as ``blocked`` (web-session automation, CLI/IDE OAuth impersonation,
  reverse-engineered proxies, terms that prohibit proxy use, coding-plan quotas) or ``unsupported`` (no
  adapter for their protocol yet) are stored with that status and reason, so users see why they are not
  connectable; connection and routing refuse them server-side.
- Hand-curated seeds in ``registry/catalog.py`` always win: for those providers the import only adds missing
  models (as ``catalog``) and the advertised free tier.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import UTC, datetime
from functools import lru_cache
from pathlib import Path
from typing import Any

from oasis_route.domain.enums import QuotaPeriod, QuotaUnit

DATA_FILE = Path(__file__).parent / "data" / "omniroute_catalog.json"
CATALOG_LIFECYCLE = "catalog"
# Lifecycles that are never listed on /v1/models nor dispatched to.
UNROUTABLE_LIFECYCLES = ("removed", CATALOG_LIFECYCLE)
PROVIDER_STATUSES = ("active", "blocked", "unsupported")


@dataclass(frozen=True)
class ImportedProvider:
    id: str
    name: str
    status: str
    status_reason: str | None
    protocol: str | None
    base_url: str | None
    raw: dict[str, Any]

    @property
    def adapter_key(self) -> str:
        return "anthropic" if self.protocol == "anthropic_messages" else "openai_compatible"

    @property
    def models(self) -> list[dict[str, Any]]:
        return list(self.raw.get("models") or [])

    def catalog_facts(self, source: dict[str, Any]) -> dict[str, Any]:
        r = self.raw
        return {
            "source": "omniroute",
            "omniroute_id": r.get("omniroute_id"),
            "status": self.status,
            "status_reason": self.status_reason,
            "protocol": self.protocol,
            "base_url": self.base_url,
            "models_url": r.get("models_url"),
            "auth": r.get("auth") or {},
            "extra_headers": r.get("extra_headers") or {},
            "website": r.get("website"),
            "auth_hint": r.get("auth_hint"),
            "free_tier": r.get("free_tier") or {},
            "model_count": len(self.models),
            "provenance": {
                **(r.get("provenance") or {}),
                "commit": source.get("commit"),
                "imported_at": source.get("imported_at"),
                "license": source.get("license"),
                "verification": "advertised",
            },
        }


@lru_cache(maxsize=1)
def load() -> dict[str, Any]:
    if not DATA_FILE.exists():  # pragma: no cover - packaging error
        return {"source": {}, "providers": [], "local_servers": []}
    data: dict[str, Any] = json.loads(DATA_FILE.read_text(encoding="utf-8"))
    return data


def source() -> dict[str, Any]:
    return dict(load().get("source") or {})


def providers() -> list[ImportedProvider]:
    out = []
    for p in load().get("providers") or []:
        status = p.get("status") if p.get("status") in PROVIDER_STATUSES else "unsupported"
        out.append(
            ImportedProvider(
                id=str(p["id"]),
                name=str(p.get("name") or p["id"]),
                status=str(status),
                status_reason=p.get("status_reason"),
                protocol=p.get("protocol"),
                base_url=p.get("base_url"),
                raw=p,
            )
        )
    return out


def get(provider_id: str) -> ImportedProvider | None:
    return next((p for p in providers() if p.id == provider_id), None)


def local_servers() -> list[dict[str, Any]]:
    return list(load().get("local_servers") or [])


def model_row(m: dict[str, Any], src: dict[str, Any]) -> dict[str, Any]:
    """Keyword arguments for a ``Model`` row built from an imported model entry."""
    pricing: dict[str, Any] = {}
    price = m.get("price")
    if isinstance(price, dict):
        pricing = {
            "prompt_usd_per_mtok": price.get("input_usd_per_mtok"),
            "completion_usd_per_mtok": price.get("output_usd_per_mtok"),
            "source": "omniroute_catalog",
            "verified": False,
            "observed_at": src.get("free_catalog_curated_at") or src.get("imported_at"),
        }
    ft = m.get("free_tier")
    catalog = {
        "source": "omniroute",
        "verification": "advertised",
        "free_tier": ft or None,
        "commit": src.get("commit"),
        "curated_at": src.get("free_catalog_curated_at"),
    }
    ctx = m.get("context_window")
    out_tok = m.get("max_output_tokens")
    return {
        "upstream_id": str(m["upstream_id"])[:200],
        "display_name": str(m.get("display_name") or m["upstream_id"])[:200],
        "aliases": [str(a) for a in m.get("aliases") or []],
        "capabilities": dict(m.get("capabilities") or {"source": "omniroute_catalog"}),
        "context_window": int(ctx) if isinstance(ctx, int | float) and ctx > 0 else None,
        "max_output_tokens": int(out_tok) if isinstance(out_tok, int | float) and out_tok > 0 else None,
        "lifecycle": CATALOG_LIFECYCLE,
        "quality": {},
        "pricing": pricing,
        "catalog": catalog,
    }


def offer_rows(p: ImportedProvider, src: dict[str, Any]) -> list[dict[str, Any]]:
    """Advertised free-tier offers (one per shared pool) for the review queue and advertised capacity."""
    ft = p.raw.get("free_tier") or {}
    rows = []
    for pool in ft.get("pools") or []:
        free_type = str(pool.get("free_type") or "")
        if free_type == "discontinued":
            continue
        claims: list[dict[str, Any]] = []
        monthly = int(pool.get("monthly_tokens") or 0)
        credit = int(pool.get("credit_tokens") or 0)
        if monthly > 0 and free_type.startswith("recurring"):
            claims.append(
                {
                    "unit": QuotaUnit.TOTAL_TOKENS.value,
                    "period": QuotaPeriod.MONTH.value,
                    "limit": monthly,
                    "source": "omniroute_catalog",
                    "text": f"about {monthly:,} tokens/month (research snapshot estimate)",
                }
            )
        if credit > 0:
            claims.append(
                {
                    "unit": QuotaUnit.TOTAL_TOKENS.value,
                    "period": QuotaPeriod.ONE_TIME.value,
                    "limit": credit,
                    "source": "omniroute_catalog",
                    "text": f"one-time {credit:,} tokens (research snapshot estimate)",
                }
            )
        key = str(pool.get("pool_key") or p.id)
        rows.append(
            {
                "dedupe_key": f"omniroute:{p.id}:{key}"[:300],
                "title": f"{p.name} free tier ({free_type or 'unspecified'}) — advertised",
                "access_mode": "free_tier",
                # Blocked/unsupported providers are visible but can never be reviewed into connectable.
                "state": "discovered" if p.status == "active" else "ineligible",
                "eligibility_reasons": [] if p.status == "active" else [p.status_reason or p.status],
                "credit_type": "one_time" if free_type == "one-time-initial" else "recurring",
                "quota_claims": claims,
                "confidence": 0.2,
                "offer_class": "free_tier",
                "access_path": "api_key",
                "terms_url": None,
                "onboarding_url": p.raw.get("website"),
                "links": {"website": p.raw.get("website"), "evidence": ft and p.raw.get("provenance")},
                "billing": {"free_type": free_type, "tos_verdict": ft.get("tos_verdict")},
                "evidence_url": (p.raw.get("provenance") or {}).get("free_catalog_url")
                or src.get("repository"),
                "excerpt": (ft.get("note") or "")[:1000],
            }
        )
    return rows


def now() -> datetime:
    return datetime.now(UTC)
